-- download_tasks
create table public.download_tasks (
    id bigint generated by default as identity not null,
    task_name text not null,
    source_url text not null,
    status text not null default 'idle'::text,
    progress_percent integer not null default 0,
    download_speed text not null default '0 MB/s'::text,
    status_message text not null default 'Waiting...'::text,
    created_at timestamp with time zone not null default now(),
    is_cancelled boolean not null default false,
    trailer_url text null,
    normalized_task_name text not null,
    task_year text null,
    fallback_urls text[] null,
    constraint download_tasks_pkey primary key (id),
    constraint download_tasks_task_name_key unique (task_name)
) TABLESPACE pg_default;

create unique INDEX IF not exists unique_task_norm_year on public.download_tasks using btree (normalized_task_name, task_year) TABLESPACE pg_default;

create index IF not exists idx_download_tasks_status on public.download_tasks using btree (status) TABLESPACE pg_default;

create trigger fill_task_norm BEFORE INSERT
or
update OF task_name on download_tasks for EACH row
execute FUNCTION trg_fill_task_norm ();